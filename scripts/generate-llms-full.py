"""Builds llms-full.txt (a single AI-readable documentation file) from the GitHub wiki.

Usage:
    git clone https://github.com/gunpal5/Google_GenerativeAI.wiki.git ../Google_GenerativeAI.wiki
    python scripts/generate-llms-full.py ../Google_GenerativeAI.wiki llms-full.txt

Pages are emitted in the order of the wiki sidebar (_Sidebar.md). Pages not linked from the sidebar are skipped.
"""
import os
import re
import sys

HEADER = """# Google GenerativeAI .NET SDK (Google_GenerativeAI) - full documentation

> Unofficial .NET SDK for Google Gemini (Gemini API / Google AI Studio) and Vertex AI. NuGet packages:
> Google_GenerativeAI, Google_GenerativeAI.Tools, Google_GenerativeAI.Auth, Google_GenerativeAI.Microsoft,
> Google_GenerativeAI.Web, Google_GenerativeAI.Live. This file concatenates the project wiki
> (https://github.com/gunpal5/Google_GenerativeAI/wiki) for use by AI coding assistants.
> Generated by scripts/generate-llms-full.py - do not edit by hand.
"""


def main(wiki_dir: str, output: str) -> None:
    sidebar = open(os.path.join(wiki_dir, "_Sidebar.md"), encoding="utf-8").read()
    pages = []
    for name in re.findall(r"\]\(([^)\s]+(?:\([^)]*\))?[^)\s]*)\)", sidebar):
        if name.startswith("http") or name in pages:
            continue
        if os.path.exists(os.path.join(wiki_dir, name + ".md")):
            pages.append(name)

    parts = [HEADER]
    for name in pages:
        text = open(os.path.join(wiki_dir, name + ".md"), encoding="utf-8-sig").read().strip()
        # Turn relative wiki links into absolute URLs so they stay meaningful outside the wiki.
        text = re.sub(r"\]\((?!https?:|#)([^)\s]+(?:\([^)]*\))?[^)\s]*)\)",
                      lambda m: f"](https://github.com/gunpal5/Google_GenerativeAI/wiki/{m.group(1)})", text)
        parts.append(f"\n\n---\n\n<!-- Source: https://github.com/gunpal5/Google_GenerativeAI/wiki/{name} -->\n\n{text}\n")

    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(parts))
    print(f"Wrote {output} from {len(pages)} pages")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
