"""Updates the SDK's DTOs to match python-genai (no new features).

What it changes:
  * Adds fields that python-genai has but an existing SDK type is missing.
  * Adds enum values that python-genai has but an existing SDK enum is missing.
  * Marks fields [Obsolete] when python-genai removed them since the last sync.
  * Creates a new DTO class or enum ONLY when a newly added field needs it (generated from python-genai's
    definition, placed in src/GenerativeAI/Types/Generated/ and registered in TypesSerializerContext).

It never adds client methods, never touches types that no SDK type references, and skips anything it cannot map
confidently (for example union types); skipped items are listed in the report for a person to handle.

The code is always generated by this script. When ANTHROPIC_API_KEY is set (and the `anthropic` package is installed),
Claude Haiku reviews the proposals first (see dto_review.py): it can leave out proposals that are Python-only, writes
the XML documentation summaries and writes the pull request summary. Without a key every proposal is kept and
python-genai's descriptions are used.

Usage:
  python scripts/drift/update_dtos.py [--apply] [--report report.md] [--no-ai]

Without --apply it only prints what it would change. Apart from the optional review it uses only the standard library.
"""
