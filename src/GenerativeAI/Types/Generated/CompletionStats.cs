using System.Text.Json;
using System.Text.Json.Serialization;

namespace GenerativeAI.Types;

/// <summary>
/// Success and error statistics for processing multiple entities in a batch. This data type is not supported in
/// the Gemini API.
/// </summary>
/// <remarks>Generated from python-genai by scripts/drift/update_dtos.py.</remarks>
public class CompletionStats
{
    /// <summary>
    /// Output only. The number of entities for which an error was encountered.
    /// </summary>
    [JsonPropertyName("failedCount")]
    [JsonNumberHandling(JsonNumberHandling.AllowReadingFromString)]
    public long? FailedCount { get; set; }

    /// <summary>
    /// Output only. The number of entities that were not finished, either successfully or with a failure. The value
    /// is negative when the total is unknown.
    /// </summary>
    [JsonPropertyName("incompleteCount")]
    [JsonNumberHandling(JsonNumberHandling.AllowReadingFromString)]
    public long? IncompleteCount { get; set; }

    /// <summary>
    /// Output only. The number of entities that were processed successfully.
    /// </summary>
    [JsonPropertyName("successfulCount")]
    [JsonNumberHandling(JsonNumberHandling.AllowReadingFromString)]
    public long? SuccessfulCount { get; set; }

    /// <summary>
    /// Output only. The number of successful forecast points generated by a forecasting model in batch prediction.
    /// </summary>
    [JsonPropertyName("successfulForecastPointCount")]
    [JsonNumberHandling(JsonNumberHandling.AllowReadingFromString)]
    public long? SuccessfulForecastPointCount { get; set; }
}
