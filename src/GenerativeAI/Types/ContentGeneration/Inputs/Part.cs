using System.Text.Json.Serialization;

namespace GenerativeAI.Types;

/// <summary>
/// A datatype containing media that is part of a multi-part <see cref="Content"/> message.
/// A <see cref="Part"/> consists of data which has an associated datatype.<br/>
/// A <see cref="Part"/> must have a fixed IANA MIME type identifying the type and subtype of the media
/// if the <see cref="Part.InlineData"/> field is filled with raw bytes.
/// </summary>
/// <seealso href="https://ai.google.dev/api/caching#Part">See Official Documentation</seealso>
public class Part
{
    /// <summary>
    /// Inline text.
    /// </summary>
    [JsonPropertyName("text")]
    public string? Text { get; set; } 

    /// <summary>
    /// Inline media bytes.
    /// </summary>
    [JsonPropertyName("inlineData")]
    public Blob? InlineData { get; set; } 

    /// <summary>
    /// A predicted <see cref="FunctionCall"/> returned from the model that contains a string
    /// representing the <see cref="FunctionDeclaration.Name"/> with the arguments and their values.
    /// </summary>
    [JsonPropertyName("functionCall")]
    public FunctionCall? FunctionCall { get; set; } 

    /// <summary>
    /// The result output of a <see cref="FunctionCall"/> that contains a string representing the
    /// <see cref="FunctionDeclaration.Name"/> and a structured JSON object containing any output
    /// from the function is used as context to the model.
    /// </summary>
    [JsonPropertyName("functionResponse")]
    public FunctionResponse? FunctionResponse { get; set; } 

    /// <summary>
    /// URI based data.
    /// </summary>
    [JsonPropertyName("fileData")]
    public FileData? FileData { get; set; } 

    /// <summary>
    /// Code generated by the model that is meant to be executed.
    /// </summary>
    [JsonPropertyName("executableCode")]
    public ExecutableCode? ExecutableCode { get; set; } 

    /// <summary>
    /// Result of executing the <see cref="ExecutableCode">ExecutableCode</see>.
    /// </summary>
    [JsonPropertyName("codeExecutionResult")]
    public CodeExecutionResult? CodeExecutionResult { get; set; }
    
    /// <summary>
    /// Metadata for a given video.
    /// </summary>
    [JsonPropertyName("videoMetadata")]
    public VideoMetadataResult? VideoMetadata { get; set; }

    /// <summary>
    /// Represents a structured part of content that can include various types of data,
    /// such as plain text, inline data, function calls, or code execution details.
    /// </summary>
    public Part()
    {
        
    }

    /// <summary>
    /// Represents a component of a multi-part message in content processing. A Part includes media
    /// or data of various forms such as text, binary data, function invocation, or code execution details.
    /// Each Part is associated with a specific data type.
    /// </summary>
    public Part(string text)
    {
        this.Text = text;
    }
    
    /// <summary>
    /// Indicates if the part is thought from the model.
    /// </summary>
    [JsonPropertyName("thought")]
    public bool? Thought { get; set; }

    /// <summary>
    /// An opaque signature for the thought so it can be reused in subsequent requests.
    /// A base64-encoded string.
    /// </summary>
    [JsonPropertyName("thoughtSignature")]
    public string? ThoughtSignature { get; set; }

    /// <summary>
    /// Media resolution for this part. Overrides GenerationConfig.MediaResolution for this part.
    /// </summary>
    [JsonPropertyName("mediaResolution")]
    public PartMediaResolution? MediaResolution { get; set; }

    /// <summary>
    /// How the model processes this part's media.
    /// </summary>
    [JsonPropertyName("mediaProcessing")]
    public MediaProcessing? MediaProcessing { get; set; }

    /// <summary>
    /// A call to a server-side tool made by the model. Only returned when ToolConfig.IncludeServerSideToolInvocations is true.
    /// </summary>
    [JsonPropertyName("toolCall")]
    public ToolCall? ToolCall { get; set; }

    /// <summary>
    /// The result of a server-side tool call. Only returned when ToolConfig.IncludeServerSideToolInvocations is true.
    /// </summary>
    [JsonPropertyName("toolResponse")]
    public ToolResponse? ToolResponse { get; set; }

    /// <summary>
    /// Speaker and style metadata for generated speech.
    /// </summary>
    [JsonPropertyName("speechMetadata")]
    public SpeechMetadata? SpeechMetadata { get; set; }

    /// <summary>
    /// Custom metadata attached to the part (Gemini API only).
    /// </summary>
    [JsonPropertyName("partMetadata")]
    public System.Text.Json.Nodes.JsonObject? PartMetadata { get; set; }

    /// <summary>
    /// Transcript of the audio in this part.
    /// </summary>
    [JsonPropertyName("audioTranscription")]
    public Transcription? AudioTranscription { get; set; }

    /// <summary>
    /// Metadata describing the audio content supplied in inline data or file data, used to configure audio
    /// preprocessing.
    /// </summary>
    [JsonPropertyName("audioMetadata")]
    public AudioMetadata? AudioMetadata { get; set; }

    /// <summary>
    /// Metadata describing the document content supplied in inline data or file data, used to configure document
    /// preprocessing.
    /// </summary>
    [JsonPropertyName("documentMetadata")]
    public DocumentMetadata? DocumentMetadata { get; set; }

    /// <summary>
    /// Metadata describing the spreadsheet content supplied in inline data or file data, used to configure
    /// spreadsheet preprocessing.
    /// </summary>
    [JsonPropertyName("spreadsheetMetadata")]
    public SpreadsheetMetadata? SpreadsheetMetadata { get; set; }
}

/// <summary>
/// Metadata describes the input video content.
/// Describes how the video in the Part should be used by the model.
/// </summary>
public class VideoMetadataResult
{
    /// <summary>
    /// Optional. The frame rate of the video sent to the model.
    /// If not specified, the default value will be 1.0. The fps range is (0.0, 24.0].
    /// </summary>
    [JsonPropertyName("fps")]
    public float? Fps { get; set; }

    /// <summary>
    /// Optional. The start offset of the video.
    /// </summary>
    [JsonPropertyName("startOffset")]
    public string? StartOffset { get; set; }

    /// <summary>
    /// Optional. The end offset of the video.
    /// </summary>
    [JsonPropertyName("endOffset")]
    public string? EndOffset { get; set; }

    /// <summary>
    /// Content layers to return for the video. If none are given, the service returns frames and audio.
    /// </summary>
    [JsonPropertyName("contentLayers")]
    public List<VideoMetadataContentLayer>? ContentLayers { get; set; }
}
    
   